def _rot(a, b, c):
    ca, sa, cb, sb, cc, sc = (
        math.cos(a),
        math.sin(a),
        math.cos(b),
        math.sin(b),
        math.cos(c),
        math.sin(c),
    )
    rx = np.array([[1, 0, 0], [0, ca, -sa], [0, sa, ca]])
    ry = np.array([[cb, 0, sb], [0, 1, 0], [-sb, 0, cb]])
    rz = np.array([[cc, -sc, 0], [sc, cc, 0], [0, 0, 1]])
    return rz @ ry @ rx


def _render_2d(cv2, name, rng):
    fg, bg = PAIRS_2D[int(rng.integers(len(PAIRS_2D)))]
    ang = float(rng.uniform(0, 2 * math.pi))
    scale = float(rng.uniform(0.55, 0.8)) * SIZE / 2
    off = rng.uniform(-6, 6, 2)
    img = np.full((SIZE, SIZE, 3), bg, np.uint8)
    cx, cy = SIZE / 2 + off[0], SIZE / 2 + off[1]
    rot = np.array([[math.cos(ang), -math.sin(ang)], [math.sin(ang), math.cos(ang)]])

    def tx(pts, s=scale):
        p = np.array(pts, float) @ rot.T * s + (cx, cy)
        return np.round(p).astype(np.int32)

    spec = SHAPES_2D[name]
    if spec is None:  # dot
        cv2.circle(
            img, (int(round(cx)), int(round(cy))), int(rng.integers(4, 8)), fg, -1, cv2.LINE_8
        )
    elif spec == "ring":
        circ = _arc(0, 2 * math.pi, n=96)[:-1]
        cv2.fillPoly(img, [tx(circ)], fg, cv2.LINE_8)
        cv2.fillPoly(img, [tx(circ, scale * 0.6)], bg, cv2.LINE_8)
    elif spec == "crescent":
        circ = _arc(0, 2 * math.pi, n=96)[:-1]
        cv2.fillPoly(img, [tx(circ)], fg, cv2.LINE_8)
        cv2.fillPoly(img, [tx([(x * 0.85 + 0.4, y * 0.85 - 0.1) for x, y in circ])], bg, cv2.LINE_8)
    else:
        cv2.fillPoly(img, [tx(p) for p in spec], fg, cv2.LINE_8)
    return img


def _render_3d(cv2, name, rng):
    colour = np.array(COLOURS_3D[int(rng.integers(len(COLOURS_3D)))], float)
    bg = BGS_3D[int(rng.integers(len(BGS_3D)))]
    r = _rot(
        float(rng.uniform(0.35, 1.2)),
        float(rng.uniform(-0.6, 0.6)),
        float(rng.uniform(0, 2 * math.pi)),
    )
    faces = [f @ r.T for f in _mesh(name)]
    allv = np.vstack(faces)
    ext = np.abs(allv[:, :2]).max()
    scale = float(rng.uniform(0.6, 0.8)) * (SIZE / 2) / ext
    img = np.full((SIZE, SIZE, 3), bg, np.uint8)
    order = sorted(range(len(faces)), key=lambda i: faces[i][:, 2].mean())  # far (low z) first
    for i in order:
        f = faces[i]
        n = np.cross(f[1] - f[0], f[2] - f[0])
        nn = np.linalg.norm(n)
        if nn < 1e-12:
            n = np.cross(f[2] - f[0], f[-1] - f[0])
            nn = np.linalg.norm(n)
            if nn < 1e-12:
                continue
        lam = abs(float(n @ LIGHT) / nn)
        c = tuple(int(v) for v in np.round(colour * (AMBIENT + (1 - AMBIENT) * lam)))
        pts = np.round(f[:, :2] * scale + SIZE / 2).astype(np.int32)
        cv2.fillPoly(img, [pts], c, cv2.LINE_8)
    return img


def classes() -> list:
    return [(n, 2) for n in SHAPES_2D] + [(n, 3) for n in SHAPES_3D]


def render(name, dim, seed, n):
    import cv2

    out = []
    for k in range(n):
        rng = np.random.default_rng([seed, abs(hash_name(name)), k])
        out.append(_render_2d(cv2, name, rng) if dim == 2 else _render_3d(cv2, name, rng))
    return out


def hash_name(name: str) -> int:
    return int(hashlib.sha256(name.encode()).hexdigest()[:8], 16)


def _sha(arr) -> str:
    return hashlib.sha256(np.ascontiguousarray(arr).tobytes()).hexdigest()[:16]


# ---------------------------------------------------------------- wordnet + bridge


def _wordnet():
    """lemma -> 'n<offset>' for the first noun.shape (25) sense, else first noun.artifact (06)."""
    if not WORDNET.exists():
        return None
    shape, art = {}, {}
    with open(WORDNET, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if line.startswith("  "):
                continue
            p = line.split(" ")
            lex, cnt = p[1], int(p[3], 16)
            tgt = shape if lex == "25" else art if lex == "06" else None
            if tgt is None:
                continue
            for i in range(cnt):
                w = p[4 + 2 * i].lower()
                tgt.setdefault(w, "n" + p[0])
    return shape, art


def _bridge(name, bridge):
    term = BRIDGE_TERM.get(name, name)
    for e in bridge:
        forms = [x.get("name") for x in e.get("form_3d", [])] + list(e.get("shape_2d", []))
        if term in forms:
            return {
                "form_3d": [x.get("name") for x in e.get("form_3d", [])],
                "shape_2d": list(e.get("shape_2d", [])),
                "objects": [x.get("name") for x in e.get("objects", [])],
            }
    return None


def build():
    """Return (files {relpath: png bytes}, index dict, memory arrays, memory header)."""
    import cv2

    sys.path.insert(0, str(ROOT))
    import recognize

    wm = json.loads((ROOT / "library" / "word_map.json").read_text(encoding="utf-8"))
    bridge = wm.get("shape_bridge", [])
    wn = _wordnet()
    files, entries = {}, []
    images = {}
    hu_rows, hu_lab = [], []
    names = [n for n, _ in classes()]
    for name, dim in classes():
        imgs = render(name, dim, SEED, VARIANTS)
        images[name] = imgs
        rel = []
        for k, img in enumerate(imgs):
            ok, buf = cv2.imencode(".png", img, [cv2.IMWRITE_PNG_COMPRESSION, 9])
            assert ok
            p = f"{dim}d/{name}/{k}.png"
            files[p] = buf.tobytes()
            rel.append({"file": p, "sha": _sha(img)})
            f = recognize.shape_features(img)
            if f is not None:
                hu_rows.append(f)
                hu_lab.append(names.index(name))
        lemma = WORDNET_LEMMA.get(name, name)
        syn = None
        if wn and lemma:
            syn = wn[0].get(lemma) or wn[1].get(lemma)
        entries.append(
            {
                "name": name,
                "dim": dim,
                "variants": rel,
                "grid_shape_name": GRID_NAME.get(name),
                "bridge": _bridge(name, bridge),
                "wordnet_synset": syn,
                "stamp": {"stage": "instance", "source": SOURCE, "seed": SEED},
                "standing": "none",
            }
        )
    index = {
        "header": {
            "note": "These images are generated by this repository (library/build_shapes.py); "
            "no third-party images and no third-party licence. standing: none -- a "
            "recognition is a candidate, the board decides.",
            "size": SIZE,
            "variants_per_class": VARIANTS,
            "seed": SEED,
            "held_out": f"{HELD_OUT} per class from seed {HELD_OUT_SEED}, rendered by the test, "
            "never written",
            "standing": "none",
            "wordnet": "first noun.shape sense, else first noun.artifact sense, of the lemma in "
            "WordNet 3.0 data.noun; null when the lemma has neither",
        },
        "classes": entries,
    }
    mem = recognize.build_memory(images, source=SOURCE)
    arrays = {
        "hu": np.array(hu_rows, np.float32),
        "hu_labels": np.array(hu_lab, np.int32),
        "centres": mem.centres,
        "labels": mem.labels.astype(np.int32),
        "positions": mem.positions,
    }
    header = {
        "classes": names,
        "dims": {n: d for n, d in classes()},
        "akaze_classes": mem.classes,
        "features": "abs log10 Hu moments (7) of the largest outer contour, + hole share, + solidity, "
        "+ interior shading (recognize.shape_features)",
        "stamp": {
            "stage": "regularity",
            "source": SOURCE,
            "seed": SEED,
            "standing": None,
            "akaze_sha": mem.stamp.get("sha"),
            "hu_sha": _sha(arrays["hu"]),
        },
        "raw_count": mem.raw_count,
        "n_centres": int(len(mem.centres)),
    }
    return files, index, arrays, header


def main(argv):
    files, index, arrays, header = build()
    if "--check" in argv:
        bad = []
        for p, b in files.items():
            f = OUT / p
            if (
                not f.exists()
                or hashlib.sha256(f.read_bytes()).digest() != hashlib.sha256(b).digest()
            ):
                bad.append(p)
        old = (
            json.loads((OUT / "memory.json").read_text(encoding="utf-8"))
            if (OUT / "memory.json").exists()
            else {}
        )
        if old.get("stamp") != header["stamp"]:
            bad.append("memory.json stamp")
        oi = (
            json.loads((OUT / "index.json").read_text(encoding="utf-8"))
            if (OUT / "index.json").exists()
            else {}
        )
        if oi != json.loads(json.dumps(index)):
            bad.append("index.json")
        print(f"check: {len(files)} images, {len(bad)} differ" + (f": {bad[:5]}" if bad else ""))
        return 1 if bad else 0
    for p, b in files.items():
        f = OUT / p
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(b)
    (OUT / "index.json").write_text(json.dumps(index, indent=1), encoding="utf-8")
    np.savez_compressed(OUT / "memory.npz", **arrays)
    (OUT / "memory.json").write_text(json.dumps(header, indent=1), encoding="utf-8")
    total = sum(len(b) for b in files.values())
    print(f"wrote {len(files)} images ({total} bytes), {len(index['classes'])} classes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
