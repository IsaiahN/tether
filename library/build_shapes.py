def _ngon(n, start=-math.pi / 2):
    return [
        (math.cos(start + 2 * math.pi * k / n), math.sin(start + 2 * math.pi * k / n))
        for k in range(n)
    ]


def _arc(a0, a1, rx=1.0, ry=1.0, n=48):
    return [
        (rx * math.cos(a0 + (a1 - a0) * k / n), ry * math.sin(a0 + (a1 - a0) * k / n))
        for k in range(n + 1)
    ]


def _star(points, inner):
    out = []
    for k in range(2 * points):
        r = 1.0 if k % 2 == 0 else inner
        a = -math.pi / 2 + math.pi * k / points
        out.append((r * math.cos(a), r * math.sin(a)))
    return out


def _heart():
    pts = []
    for k in range(96):
        t = 2 * math.pi * k / 96
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        pts.append((x / 17, -y / 17))
    return pts


